/** จำนวนตัวอักษรสูงสุดที่ยังพอวาดในไพ่ — เกินนี้ fallback เป็นข้อความ */
export const MAX_PIXEL_CHARS = 4;

const GLYPH_HEIGHT = 7;

/** pure: ค่าโหวต → ตารางพิกเซล (แถวความยาวเท่ากัน, "#" คือจุดสว่าง) — null เมื่อวาดไม่ได้ */
export const buildPixelGrid = (value: string): readonly string[] | null => {
  const chars = [...value.toUpperCase()];
  if (chars.length === 0 || chars.length > MAX_PIXEL_CHARS) return null;

  const selected: Array<readonly string[]> = [];
  for (const char of chars) {
    const glyph = GLYPHS[char];
    if (!glyph) return null;
    selected.push(glyph);
  }

  const rows: string[] = [];
  for (let y = 0; y < GLYPH_HEIGHT; y += 1) {
    rows.push(selected.map((glyph) => glyph[y] ?? ".").join("."));
  }
  return rows;
};

/** ความกว้างของตาราง (คอลัมน์) — ใช้ตั้ง viewBox ของ SVG */
export const pixelGridWidth = (grid: readonly string[]): number =>
  grid[0]?.length ?? 0;
